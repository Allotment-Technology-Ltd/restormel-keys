/**
 * Emit SQL to upsert AiZolo catalog rows (models + provider_model_variants) for Neon MCP,
 * `psql`, or Neon SQL editor. Reads apps/dashboard/data/model-catalog-seed.json (family === "aizolo").
 *
 * Usage:
 *   node apps/dashboard/scripts/export-aizolo-catalog-sql.mjs --out apps/dashboard/sql/aizolo-catalog-upsert.sql
 *   node apps/dashboard/scripts/export-aizolo-catalog-sql.mjs --mcp-json apps/dashboard/sql/aizolo-catalog-mcp.json
 *
 * Neon MCP: use `run_sql_transaction` with { projectId, sqlStatements: <array from --mcp-json> }.
 */
import { readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const SEED_PATH = join(__dirname, "..", "data", "model-catalog-seed.json");

function esc(s) {
  if (s == null) return "NULL";
  return `'${String(s).replace(/'/g, "''")}'`;
}

function escJson(arr) {
  if (!arr || !arr.length) return "NULL";
  return `'${JSON.stringify(arr).replace(/'/g, "''")}'::json`;
}

function modelInsert(m) {
  const modalities = escJson(m.modalities);
  const capabilities = escJson(m.capabilities);
  return `INSERT INTO models (
  id, canonical_name, family, lifecycle_state, description,
  context_window, max_output_tokens, supports_tools, supports_structured_output, supports_mcp,
  modalities, capabilities, editorial_summary,
  deprecation_date, retirement_date, replacement_model_id, source_last_verified_at
) VALUES (
  ${esc(m.id)}, ${esc(m.canonicalName)}, ${esc(m.family)}, ${esc(m.lifecycleState)}, ${esc(m.description)},
  ${m.contextWindow ?? "NULL"}, ${m.maxOutputTokens ?? "NULL"}, ${m.supportsTools ?? "NULL"}, ${m.supportsStructuredOutput ?? "NULL"}, ${m.supportsMcp ?? "NULL"},
  ${modalities}, ${capabilities}, ${m.editorialSummary != null ? esc(m.editorialSummary) : "NULL"},
  ${m.deprecationDate ?? "NULL"}, ${m.retirementDate ?? "NULL"}, ${m.replacementModelId != null ? esc(m.replacementModelId) : "NULL"}, ${m.sourceLastVerifiedAt ?? "NULL"}
)
ON CONFLICT (id) DO UPDATE SET
  canonical_name = EXCLUDED.canonical_name,
  family = EXCLUDED.family,
  lifecycle_state = EXCLUDED.lifecycle_state,
  description = EXCLUDED.description,
  context_window = EXCLUDED.context_window,
  max_output_tokens = EXCLUDED.max_output_tokens,
  supports_tools = EXCLUDED.supports_tools,
  supports_structured_output = EXCLUDED.supports_structured_output,
  supports_mcp = EXCLUDED.supports_mcp,
  modalities = EXCLUDED.modalities,
  capabilities = EXCLUDED.capabilities,
  editorial_summary = EXCLUDED.editorial_summary,
  deprecation_date = EXCLUDED.deprecation_date,
  retirement_date = EXCLUDED.retirement_date,
  replacement_model_id = EXCLUDED.replacement_model_id,
  source_last_verified_at = EXCLUDED.source_last_verified_at`;
}

function variantInsert(m, v) {
  const variantId = `${m.id}-${v.providerIntegrationType}`;
  return `INSERT INTO provider_model_variants (
  id, model_id, provider_integration_type, provider_model_id,
  availability_status, pricing_ref, rate_limit_ref, source_last_verified_at
) VALUES (
  ${esc(variantId)}, ${esc(m.id)}, ${esc(v.providerIntegrationType)}, ${esc(v.providerModelId)},
  ${v.availabilityStatus != null ? esc(v.availabilityStatus) : "NULL"}, ${v.pricingRef != null ? esc(v.pricingRef) : "NULL"}, ${v.rateLimitRef != null ? esc(v.rateLimitRef) : "NULL"}, ${v.sourceLastVerifiedAt ?? "NULL"}
)
ON CONFLICT (id) DO UPDATE SET
  provider_model_id = EXCLUDED.provider_model_id,
  availability_status = EXCLUDED.availability_status,
  pricing_ref = EXCLUDED.pricing_ref,
  rate_limit_ref = EXCLUDED.rate_limit_ref,
  source_last_verified_at = EXCLUDED.source_last_verified_at`;
}

function main() {
  const outIdx = process.argv.indexOf("--out");
  const mcpIdx = process.argv.indexOf("--mcp-json");
  const outPath = outIdx >= 0 ? process.argv[outIdx + 1] : null;
  const mcpPath = mcpIdx >= 0 ? process.argv[mcpIdx + 1] : null;

  const seed = JSON.parse(readFileSync(SEED_PATH, "utf-8"));
  const aizolo = seed.models.filter((m) => m.family === "aizolo");
  if (aizolo.length === 0) {
    console.error("No models with family === 'aizolo' in model-catalog-seed.json. Run sync:aizolo-seed first.");
    process.exit(1);
  }

  const statements = ["BEGIN"];
  for (const m of aizolo) {
    statements.push(modelInsert(m));
  }
  for (const m of aizolo) {
    for (const v of m.variants ?? []) {
      statements.push(variantInsert(m, v));
    }
  }
  statements.push("COMMIT");

  const header = "-- AiZolo catalog upsert (generated by export-aizolo-catalog-sql.mjs)\n\n";
  const sqlFile = header + statements.map((s) => `${s};`).join("\n\n") + "\n";

  if (mcpPath) {
    writeFileSync(mcpPath, `${JSON.stringify({ sqlStatements: statements }, null, 2)}\n`, "utf-8");
    console.error(`Wrote Neon MCP payload (${statements.length} statements) to ${mcpPath}`);
  }

  if (outPath) {
    writeFileSync(outPath, sqlFile, "utf-8");
    console.error(`Wrote ${aizolo.length} AiZolo models (${sqlFile.length} bytes) to ${outPath}`);
  }

  if (!outPath && !mcpPath) {
    process.stdout.write(sqlFile);
  }
}

main();
