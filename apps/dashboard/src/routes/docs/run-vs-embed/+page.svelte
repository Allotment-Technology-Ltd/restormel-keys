    <code>@restormel/testing-*</code> for CI goals, <code>@restormel/ui-graph-svelte</code> for canvas UIs. Start with the
    <a href="/docs/quickstart">suite quickstart</a>, then open the capability doc tree you need.
  </p>

  <p>You do not need to read every doc page upfront — use <a href="/keys/docs/search">search</a> when you are stuck.</p>
